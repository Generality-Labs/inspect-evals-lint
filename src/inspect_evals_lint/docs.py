"""Generate the rule documentation from the registry, so it cannot drift from the code.

``python -m inspect_evals_lint.docs`` writes ``docs/rules/<code>.md`` (one page
per rule, from its docstring), ``docs/CHECKS.md`` (the index, grouped by
category), ``docs/index.md`` (the README as the site's front page) and the
configuration table in ``README.md`` (from
:class:`~inspect_evals_lint.config.LintConfig` field metadata). The ``docs/``
directory is published with mkdocs by ``.github/workflows/docs.yml``. ``--check``
exits non-zero when a committed file differs from what would be generated;
pre-commit runs it so the docs are always current.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Mapping
from dataclasses import fields
from pathlib import Path
from typing import cast

from inspect_evals_lint.config import PRESETS, LintConfig
from inspect_evals_lint.registry import CATEGORIES, Rule, rules

CATEGORY_TITLES: dict[str, str] = {
    "file_structure": "File structure",
    "code_quality": "Code quality",
    "tests": "Tests",
    "best_practices": "Best practices",
}

README_TABLE_START = "<!-- config-table:start -->"
README_TABLE_END = "<!-- config-table:end -->"
GENERATED_NOTE = (
    "<!-- Generated by `python -m inspect_evals_lint.docs`; edit the source, not this file. -->"
)


_FENCE = "\x00fence\x00"


def _markdown(text: str) -> str:
    """Docstrings use RST double backticks for inline code; the pages are Markdown.

    Code fences are three backticks and must survive the conversion.
    """
    return text.replace("```", _FENCE).replace("``", "`").replace(_FENCE, "```")


def formatted(markdown: str) -> str:
    """``markdown`` as the repository's mdformat hook would write it, so generated files are stable under it."""
    import mdformat

    text = mdformat.text  # pyright: ignore[reportUnknownMemberType, reportUnknownVariableType]
    return text(markdown, options={"wrap": "no", "number": True}, extensions={"gfm"})


def rule_page(rule: Rule) -> str:
    """The Markdown page for one rule."""
    facts = [
        f"**Category:** {rule.category}",
        f"**Applies to:** {', '.join(sorted(rule.scopes))}",
    ]
    if rule.allowlist:
        facts.append(f"**Allowlist:** `[tool.inspect-evals-lint.allowlists.{rule.name}]`")
    doc = _markdown(rule.doc)
    # The first paragraph of the docstring restates the summary; the page has it as a lead already.
    body = doc.split("\n\n", 1)[1] if "\n\n" in doc else ""
    lines = [
        f"# {rule.code}: {rule.name}",
        "",
        GENERATED_NOTE,
        "",
        _markdown(rule.summary) + ".",
        "",
        " · ".join(facts),
        "",
        body.strip(),
        "",
        f"Suppress on a line with `# inspect-evals-lint: ignore[{rule.code}]` or `ignore[{rule.name}]`; "
        f"select or ignore it in configuration by either, or by the prefix `{rule.code[:4]}`.",
        "",
    ]
    return "\n".join(lines)


def index_page() -> str:
    """``docs/CHECKS.md``: every rule by category, with links to the pages."""
    lines = [
        "# Rule index",
        "",
        GENERATED_NOTE,
        "",
        "Every rule has a code (`IEFS`, `IECQ`, `IETS`, `IEBP` prefixes for the four categories below) and a name; either is accepted by `--select`, `--ignore` and in suppression comments, and a prefix selects a whole category. A rule reports one diagnostic per site it finds something wrong at, each with a file and, where the finding is in a file's contents, a line and column. A rule with nothing to point at reports `pass`, or `skip` with the reason. Diagnostics are `fail` or `warn`; only `fail` makes the run exit non-zero. `inspect-evals-lint --explain <code>` prints the same text as a rule's page.",
        "",
    ]
    for category in CATEGORIES:
        lines += [
            f"## {CATEGORY_TITLES[category]}",
            "",
            "| Code | Rule | Applies to | Summary |",
            "| --- | --- | --- | --- |",
        ]
        for rule in (r for r in rules() if r.category == category):
            scope = "eval, helper" if "helper" in rule.scopes else "eval"
            lines.append(
                f"| [{rule.code}](rules/{rule.code}.md) | `{rule.name}` | {scope} | {_markdown(rule.summary)} |"
            )
        lines.append("")
    helper_rules = ", ".join(f"`{r.name}`" for r in rules() if "helper" in r.scopes)
    eval_only = ", ".join(f"`{r.name}`" for r in rules() if "helper" not in r.scopes)
    lines += [
        "## Helper packages",
        "",
        f"Directories listed in `helper-dirs` (by default `utils`) hold code that evaluations import rather than an evaluation. They run the rules about behaviour and not the ones about an evaluation's structure and registration. Run: {helper_rules}. Not run: {eval_only}. Every rule declares its scopes in its `@rule` decorator, so a new rule decides up front whether shared code is in scope.",
        "",
        "## Categories",
        "",
        "Each rule belongs to one of exactly four categories, the sections above. The JSON output and `registry.CATEGORIES` expose them, and downstream tooling (badges, the register lint service) is built around that fixed set. A new rule joins one of the four; adding a category would be a breaking change.",
        "",
        "## Suppression",
        "",
        "- Line: `# inspect-evals-lint: ignore[<rule>]` on the offending line, or on any line of a multi-line statement; names, codes and code prefixes, comma-separated. `ignore` without a bracketed list is a configuration error. In a Dockerfile, on the line above the instruction.",
        "- File: `# inspect-evals-lint: ignore-file[<rule>]` within the first ten lines.",
        '- Paths: `per-file-ignores = { "<glob>" = ["<rule>"] }` in `[tool.inspect-evals-lint]`.',
        '- Never read: `exclude = ["<glob>"]` keeps files out of the AST-based rules entirely, for code shipped into a sandbox.',
        "",
        "Suppressed findings still appear in reports, marked `[suppressed]`, and count as passing. The former `noautolint` comments and `.noautolint` files are rejected with a message naming the replacement.",
        "",
    ]
    return "\n".join(lines)


def _format_value(value: object) -> str:
    if value is None:
        return "unset"
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if isinstance(value, str):
        return f"`{value}`" if value else '`""`'
    if isinstance(value, frozenset):
        items: list[str] = sorted(str(v) for v in value)  # type: ignore[arg-type]
        return "`[" + ", ".join(f'"{v}"' for v in items) + "]`"
    if isinstance(value, tuple):
        seq = cast(tuple[object, ...], value)
        if not seq:
            return "`[]`"
        if all(isinstance(v, str) for v in seq):
            return "`[" + ", ".join(f'"{v}"' for v in seq) + "]`"
        return "`{}`"
    if isinstance(value, Mapping):
        table = cast(Mapping[str, object], value)
        if not table:
            return "`{}`"
        return "`{ " + ", ".join(f"{k} = {_toml_value(v)}" for k, v in table.items()) + " }`"
    return f"`{value}`"


def _toml_value(value: object) -> str:
    """``value`` as inline TOML, for a preset's rule options; keys are written kebab-case as a user would."""
    if isinstance(value, Mapping):
        table = cast(Mapping[str, object], value)
        return (
            "{ "
            + ", ".join(f"{k.replace('_', '-')} = {_toml_value(v)}" for k, v in table.items())
            + " }"
        )
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return f'"{value}"'
    return str(value)


def config_table() -> str:
    """The README configuration table: one row per :class:`LintConfig` field, one column per preset."""
    presets = ("template", "monorepo", "register")
    lines = [
        "| Key | " + " | ".join(f"`{p}` preset" for p in presets) + " | Meaning |",
        "| --- | " + " | ".join("---" for _ in presets) + " | --- |",
    ]
    for f in fields(LintConfig):
        key = f.name.replace("_", "-")
        if f.name == "allowlists":
            key = "allowlists.<rule>"
        elif f.name == "rule_options":
            key = "<rule>"
        values = " | ".join(_format_value(getattr(PRESETS[p], f.name)) for p in presets)
        doc = _markdown(str(f.metadata.get("doc", "")))
        lines.append(f"| `{key}` | {values} | {doc} |")
    return "\n".join(lines)


def readme_with_table(readme: str) -> str:
    """``readme`` with the configuration table between the markers regenerated."""
    pattern = re.compile(re.escape(README_TABLE_START) + r"[\s\S]*?" + re.escape(README_TABLE_END))
    if not pattern.search(readme):
        raise ValueError(f"README.md has no {README_TABLE_START} / {README_TABLE_END} markers")
    replacement = f"{README_TABLE_START}\n\n{config_table()}\n\n{README_TABLE_END}"
    return pattern.sub(lambda _: replacement, readme)


REPO_BLOB = "https://github.com/Generality-Labs/inspect-evals-lint/blob/main/"
_LINK = re.compile(r"\]\(([^)#][^)]*)\)")


def site_index(readme: str, docs_dir: Path) -> str:
    """``docs/index.md``: the README as the site's front page.

    Links into ``docs/`` lose the prefix, ``docs/rules/`` points at the rules
    index, and links to other repository files go to GitHub, since the site
    only carries ``docs/``.
    """

    def rewrite(match: re.Match[str]) -> str:
        target = match.group(1)
        if target.startswith(("http://", "https://", "mailto:")):
            return match.group(0)
        if target in ("docs/rules/", "docs/rules"):
            return "](CHECKS.md)"
        if target.startswith("docs/"):
            return f"]({target[len('docs/') :]})"
        if (docs_dir / target).exists():
            return match.group(0)
        return f"]({REPO_BLOB}{target})"

    body = _LINK.sub(rewrite, readme)
    first_heading, _, rest = body.partition("\n")
    return f"{first_heading}\n\n{GENERATED_NOTE}\n{rest}"


def generated_files(root: Path) -> dict[Path, str]:
    """Every generated file and its intended content, formatted as the mdformat hook would leave it."""
    out: dict[Path, str] = {root / "docs" / "CHECKS.md": formatted(index_page())}
    for rule in rules():
        out[root / "docs" / "rules" / f"{rule.code}.md"] = formatted(rule_page(rule))
    readme = root / "README.md"
    if readme.exists():
        updated_readme = formatted(readme_with_table(readme.read_text(encoding="utf-8")))
        out[readme] = updated_readme
        out[root / "docs" / "index.md"] = formatted(site_index(updated_readme, root / "docs"))
    return out


def stale_files(root: Path) -> list[Path]:
    """Generated files whose committed content differs from what would be generated."""
    stale: list[Path] = []
    for path, content in generated_files(root).items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)
    rules_dir = root / "docs" / "rules"
    if rules_dir.is_dir():
        expected = {root / "docs" / "rules" / f"{r.code}.md" for r in rules()}
        stale.extend(sorted(p for p in rules_dir.glob("*.md") if p not in expected))
    return stale


def write(root: Path) -> list[Path]:
    """Write every generated file; remove pages for rules that no longer exist. Returns what changed."""
    changed = stale_files(root)
    for path, content in generated_files(root).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    expected = {root / "docs" / "rules" / f"{r.code}.md" for r in rules()}
    for page in (root / "docs" / "rules").glob("*.md"):
        if page not in expected:
            page.unlink()
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0] if __doc__ else None)
    parser.add_argument(
        "--root", type=Path, default=Path.cwd(), help="Repository root (default: cwd)"
    )
    parser.add_argument(
        "--check", action="store_true", help="Exit 1 if any generated file is out of date"
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if args.check:
        stale = stale_files(root)
        for path in stale:
            print(f"out of date: {path.relative_to(root)}")
        if stale:
            print("Run `uv run python -m inspect_evals_lint.docs` and commit the result.")
            return 1
        print("Generated documentation is up to date.")
        return 0
    for path in write(root):
        print(f"wrote {path.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
